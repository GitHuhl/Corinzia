/// A player's level (RMS) for a note at a dynamic, from the table
/// (between dynamics, as dB; outside the range, the nearest key).
pub fn level(instrument: usize, key: i32, d: f32) -> f32 {
    let i = instrument.min(3);
    let table = DB[i];
    if table.is_empty() {
        return 0.01;
    }
    let row = &table[(key - LOWEST[i]).clamp(0, table.len() as i32 - 1) as usize];
    let x = d.clamp(0.0, 1.0) * (DYNAMICS.len() - 1) as f32;
    let k = (x as usize).min(DYNAMICS.len() - 2);
    let db = row[k] + (x - k as f32) * (row[k + 1] - row[k]);
    10f32.powf(db / 20.0)
}
