/// A player's level (RMS) for a note at a dynamic, from the table
/// (between dynamics, as dB; outside the range, the nearest key).
/// While the table is made: every level 1 (the voices' raw output).
#[cfg(test)]
pub static RAW: std::sync::atomic::AtomicBool = std::sync::atomic::AtomicBool::new(false);

pub fn level(instrument: usize, key: i32, d: f32) -> f32 {
    #[cfg(test)]
    if RAW.load(std::sync::atomic::Ordering::Relaxed) {
        return 1.0;
    }
    let Some(row) = row(instrument, key) else { return 0.01 };
    let x = d.clamp(0.0, 1.0) * (DYNAMICS.len() - 1) as f32;
    let k = (x as usize).min(DYNAMICS.len() - 2);
    let db = row[k] + (x - k as f32) * (row[k + 1] - row[k]);
    10f32.powf(db / 20.0)
}

fn row(instrument: usize, key: i32) -> Option<&'static [f32; 5]> {
    let i = instrument.min(3);
    let table = DB[i];
    (!table.is_empty()).then(|| &table[(key - LOWEST[i]).clamp(0, table.len() as i32 - 1) as usize])
}
